/** 去掉空白与标点，避免「忽 略 以 上 指 令」这类变形绕过 */
function normalize(text) {
  return String(text || '').toLowerCase()
    .replace(/[\s\u3000\u200b-\u200d\p{P}·・…—～]/gu, '')
}

/**
 * @returns {{boundary: string, rule: string, reply: string} | null} 命中时返回拒答信息
 */
export function screenBoundary(text) {
  const normalized = normalize(text)
  if (!normalized) return null
  const hit = RULES.find(rule => rule.match(normalized))
  return hit ? { boundary: hit.boundary, rule: hit.rule, reply: BOUNDARY_REPLIES[hit.boundary] } : null
}
